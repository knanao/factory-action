/**
 * Interactive local QA for the action, runnable with no credentials and no
 * network access beyond localhost: `bun run qa`.
 *
 * The flow exercises the whole delegation chain through the real
 * `local-action` CLI (via the qa/local-action.ts wrapper, which the
 * `local-action` package script uses too), against the bundled mock APIs
 * (`qa/mock-server.ts`):
 *
 * 1. Run 1 delivers an `@factory` issue comment and must take the
 *    "new session" path: eyes reaction on the comment, session created on
 *    the mock Factory API (with `cwd` resolved from the mock computer's
 *    clone), the mention prompt posted to the session, and a tracking
 *    comment with the state marker written to the mock GitHub API.
 * 2. Run 2 re-delivers the same event (like re-running the workflow) and
 *    must take the "session reuse" path: find the tracking comment, fetch
 *    the existing session, post a follow-up, and update the comment.
 *
 * The observed API traffic and the rendered job summary are asserted, and the
 * run exits nonzero when any expectation fails. Artifacts land in `.qa/`.
 */

import { spawn } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync
} from 'node:fs'
import path from 'node:path'
import {
  MOCK_CLONE_DIR,
  SELF_LOGIN,
  startMockServer,
  type LoggedRequest
} from './mock-server.js'

const ROOT = path.resolve(import.meta.dirname, '..')
const ENV_FILE = '.qa/env'
const SUMMARY_FILE = '.qa/step-summary.md'
const EVENT_FILE = 'qa/events/issue-comment.json'

const OWNER = 'acme'
const REPO = 'widgets'
const ISSUE = 42
const COMPUTER_ID = 'cmp-local-qa'

interface RunResult {
  code: number
}

async function main(): Promise<void> {
  const event = readEvent()
  const api = await startMockServer()
  prepareWorkdir(api.port)

  console.log('Mock APIs (GitHub + Factory) listening on', api.url)
  console.log(
    'Running the action twice via local-action (issue comment #%s)',
    event.comment.id
  )
  console.log()

  const first = await runAction(api.url)
  const firstCount = api.requests().length
  const second = await runAction(api.url)

  const failures = [
    ...assertNewSession(first.code, api.requests().slice(0, firstCount), event),
    ...assertReuse(second.code, api.requests().slice(firstCount)),
    ...assertSummary()
  ]

  console.log()
  if (failures.length > 0) {
    console.error(`QA FAILED (${failures.length}):`)
    for (const failure of failures) console.error(`  - ${failure}`)
    console.error()
    console.error('Mock API request log:')
    console.error(JSON.stringify(api.requests(), null, 2))
    process.exitCode = 1
  } else {
    console.log('QA PASSED: the action is interactively runnable end-to-end.')
    console.log('  run 1: new session, prompt posted, tracking comment created')
    console.log('  run 2: session reused, follow-up posted, comment updated')
  }

  await api.close()
}

interface Event {
  comment: { id: number; body: string }
}

function readEvent(): Event {
  const raw = readFileSync(path.join(ROOT, EVENT_FILE), 'utf8')
  const event = JSON.parse(raw) as Event
  if (!Number.isInteger(event.comment?.id) || !event.comment?.body) {
    throw new Error(
      `${EVENT_FILE} must set comment.id (number) and comment.body`
    )
  }
  return event
}

/** Writes the dotenv file local-action reads and clears stale artifacts. */
function prepareWorkdir(port: number): void {
  mkdirSync(path.join(ROOT, '.qa'), { recursive: true })
  rmSync(path.join(ROOT, SUMMARY_FILE), { force: true })
  writeFileSync(path.join(ROOT, ENV_FILE), renderEnv(port))
}

function renderEnv(port: number): string {
  const base = `http://127.0.0.1:${port}`
  return [
    '# Generated by `bun run qa` — offline QA against the mock APIs.',
    '# For the manual (real credentials) variant, copy .env.example to .env.',
    'INPUT_FACTORY-API-KEY=fac-local-qa-key',
    `INPUT_COMPUTER-ID=${COMPUTER_ID}`,
    'INPUT_GITHUB-TOKEN=gh-local-qa-token',
    `INPUT_FACTORY-API-URL=${base}`,
    'INPUT_MESSAGE-TIMEOUT-MS=5000',
    `GITHUB_API_URL=${base}`,
    'GITHUB_SERVER_URL=https://github.com',
    'GITHUB_EVENT_NAME=issue_comment',
    `GITHUB_EVENT_PATH=${EVENT_FILE}`,
    `GITHUB_REPOSITORY=${OWNER}/${REPO}`,
    'GITHUB_RUN_ID=123456789',
    'GITHUB_RUN_NUMBER=1',
    'GITHUB_RUN_ATTEMPT=1',
    `GITHUB_STEP_SUMMARY=${SUMMARY_FILE}`,
    'ACTIONS_STEP_DEBUG=true',
    ''
  ].join('\n')
}

/**
 * Runs the action once through the local-action wrapper (qa/local-action.ts),
 * which sanitizes PATH for bun's node shims and pins GITHUB_API_URL to the
 * mock server.
 */
function runAction(apiUrl: string): Promise<RunResult> {
  return new Promise((resolve, reject) => {
    const child = spawn(
      process.execPath,
      [path.join(ROOT, 'qa', 'local-action.ts'), ENV_FILE],
      {
        cwd: ROOT,
        env: { ...process.env, GITHUB_API_URL: apiUrl }
      }
    )
    const tee = (chunk: Buffer): void => {
      process.stdout.write(chunk)
    }
    child.stdout?.on('data', tee)
    child.stderr?.on('data', tee)
    child.on('error', reject)
    child.on('close', (code) => resolve({ code: code ?? -1 }))
  })
}

// --- Assertions ---------------------------------------------------------------

function assertNewSession(
  code: number,
  log: LoggedRequest[],
  event: Event
): string[] {
  const failures: string[] = []
  if (code !== 0) failures.push(`run 1: local-action exited with ${code}`)

  const reaction = find(
    log,
    'POST',
    `/repos/${OWNER}/${REPO}/issues/comments/${event.comment.id}/reactions`
  )
  if (!reaction)
    failures.push('run 1: no eyes reaction on the triggering comment')
  else if (!reaction.authorized)
    failures.push('run 1: the reaction request carried no authorization')

  const created = find(log, 'POST', '/api/v0/sessions')
  if (!created) {
    failures.push('run 1: no session was created on the Factory API')
    return failures
  }
  const request = fields(created.body)
  if (request.computerId !== COMPUTER_ID)
    failures.push(
      `run 1: session created on computer '${String(request.computerId)}'`
    )
  if (request.cwd !== MOCK_CLONE_DIR)
    failures.push(
      `run 1: cwd '${String(request.cwd)}' was not resolved to the mock clone ${MOCK_CLONE_DIR}`
    )

  const sessionId = str(fields(created.response), 'sessionId')
  if (!sessionId)
    failures.push('run 1: the Factory API response has no sessionId')
  else {
    const message = find(log, 'POST', `/api/v0/sessions/${sessionId}/messages`)
    if (!message)
      failures.push(`run 1: no prompt posted to session ${sessionId}`)
    else {
      const text = str(fields(message.body), 'text') ?? ''
      if (!text.includes(event.comment.body))
        failures.push(
          'run 1: the posted prompt does not contain the comment text'
        )
    }
  }

  const tracking = find(
    log,
    'POST',
    `/repos/${OWNER}/${REPO}/issues/${ISSUE}/comments`
  )
  if (!tracking) failures.push('run 1: no tracking comment was created')
  else {
    const body = str(fields(tracking.body), 'body') ?? ''
    if (!body.includes('<!-- factory-action:state '))
      failures.push('run 1: the tracking comment lacks the state marker')
    if (sessionId && !body.includes(sessionId))
      failures.push(
        'run 1: the tracking comment does not reference the session'
      )
  }

  return failures
}

function assertReuse(code: number, log: LoggedRequest[]): string[] {
  const failures: string[] = []
  if (code !== 0) failures.push(`run 2: local-action exited with ${code}`)

  const session = find(log, 'POST', '/api/v0/sessions')
  if (session)
    failures.push(
      'run 2: a new session was created instead of reusing the tracked one'
    )

  const fetched = log.find(
    (r) => r.method === 'GET' && /^\/api\/v0\/sessions\/[^/]+$/.test(r.path)
  )
  if (!fetched)
    failures.push('run 2: the tracked session was not fetched before reuse')

  const message = log.find(
    (r) => r.method === 'POST' && /\/messages$/.test(r.path)
  )
  if (!message) failures.push('run 2: no follow-up was posted to the session')

  const updated = log.find(
    (r) =>
      r.method === 'PATCH' &&
      new RegExp(`^/repos/${OWNER}/${REPO}/issues/comments/\\d+$`).test(r.path)
  )
  if (!updated) failures.push('run 2: the tracking comment was not updated')
  else {
    const body = str(fields(updated.response), 'body') ?? ''
    if (!body.includes('Delegated (follow-up)'))
      failures.push('run 2: the comment does not show the follow-up status')
  }

  return failures
}

function assertSummary(): string[] {
  const failures: string[] = []
  const summaryPath = path.join(ROOT, SUMMARY_FILE)
  if (!existsSync(summaryPath)) {
    failures.push('no job summary was rendered')
    return failures
  }
  const summary = readFileSync(summaryPath, 'utf8')
  if (!summary.includes('https://app.factory.ai/sessions/'))
    failures.push('the job summary does not link the session')
  if (!summary.includes(SELF_LOGIN) && !summary.includes('Factory Droid'))
    failures.push('the job summary does not describe the delegation')
  return failures
}

// --- Helpers ------------------------------------------------------------------

function find(
  log: LoggedRequest[],
  method: string,
  path: string
): LoggedRequest | undefined {
  return log.find((r) => r.method === method && r.path === path)
}

function fields(value: unknown): Record<string, unknown> {
  return value && typeof value === 'object'
    ? (value as Record<string, unknown>)
    : {}
}

function str(value: Record<string, unknown>, key: string): string | undefined {
  const v = value[key]
  return typeof v === 'string' ? v : undefined
}

await main()
