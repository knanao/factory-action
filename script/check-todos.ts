/**
 * Tech-debt policy: every debt marker in code must link to a GitHub issue,
 * written as the marker followed by `(#<issue number>)` and the note. The
 * markers are the upper-case words that MARKER below matches.
 *
 * Scans the code and configuration files tracked by git (Markdown is prose and
 * is not scanned), fails on unlinked markers and prints an inventory of the
 * linked ones, also to the GitHub Actions job summary when it runs in CI.
 *
 * Usage: bun script/check-todos.ts
 */
import { appendFileSync } from 'node:fs'
import { basename, extname } from 'node:path'
import { readTracked, trackedFiles } from './lib/tracked-files.js'

// The bracketed letters keep this line from matching itself.
const MARKER = /\b(TO[D]O|FIX[M]E|HAC[K]|XX[X])\b(\(#(\d+)\))?/g

const CODE_EXTENSIONS = new Set([
  '.cjs',
  '.js',
  '.json',
  '.jsonc',
  '.mjs',
  '.sh',
  '.toml',
  '.ts',
  '.yaml',
  '.yml'
])

/** Bundled third-party code, regenerated by `bun run package`. */
const EXCLUDED_PREFIXES = ['dist/']

interface Marker {
  path: string
  line: number
  word: string
  issue?: string
  text: string
}

const markers = trackedFiles()
  .filter(isCode)
  .flatMap((path) => scan(path))
const unlinked = markers.filter((m) => m.issue === undefined)
const linked = markers.filter((m) => m.issue !== undefined)

report(linked)
if (unlinked.length > 0) {
  console.error(
    `\n${unlinked.length} tech-debt marker(s) without an issue link:\n` +
      unlinked
        .map(
          (m) =>
            `  ${m.path}:${m.line}: ${m.text}\n    write ${m.word}(#<issue>): ...`
        )
        .join('\n')
  )
  console.error('\nOpen an issue for the debt, then link it in the marker.')
  process.exit(1)
}

function isCode(path: string): boolean {
  if (EXCLUDED_PREFIXES.some((prefix) => path.startsWith(prefix))) return false
  if (CODE_EXTENSIONS.has(extname(path))) return true
  if (basename(path) === 'Dockerfile') return true
  // Extensionless executables such as .githooks/*.
  return extname(path) === '' && readTracked(path)?.startsWith('#!') === true
}

function scan(path: string): Marker[] {
  const content = readTracked(path)
  if (content === undefined || content.includes('\0')) return []
  return content.split('\n').flatMap((text, index) =>
    [...text.matchAll(MARKER)].map((m) => ({
      path,
      line: index + 1,
      word: m[1],
      issue: m[3],
      text: text.trim()
    }))
  )
}

function report(found: Marker[]): void {
  const issues = new Set(found.map((m) => m.issue))
  const heading = `Tech-debt markers: ${found.length} linked to ${issues.size} issue(s)`
  console.log(heading)
  for (const m of found) console.log(`  #${m.issue} ${m.path}:${m.line}`)

  const summaryPath = process.env.GITHUB_STEP_SUMMARY
  if (!summaryPath) return
  const rows = found.map(
    (m) =>
      `| #${m.issue} | \`${m.path}:${m.line}\` | ${m.text.replaceAll('|', '\\|')} |`
  )
  const table =
    rows.length > 0
      ? ['| Issue | Location | Marker |', '| --- | --- | --- |', ...rows]
      : ['No tech-debt markers.']
  appendFileSync(summaryPath, `### ${heading}\n\n${table.join('\n')}\n\n`)
}
